import assert from 'node:assert/strict';
import {CATALOG,SAMPLE,GOALS} from '../frontend/assets/data/mock-data.js';
import {QUESTIONS,preferenceFit} from '../frontend/assets/js/preferences.js';
import {matchTutors,matchGroups,WEIGHTS,approvedToTeach} from '../frontend/assets/js/matching.js';
import {defaultPlan,planProgress,ensurePlan} from '../frontend/assets/js/plans.js';

const student=structuredClone(SAMPLE.students.returning.request);
const tutors=structuredClone(CATALOG.tutors);
assert.equal(QUESTIONS.length,3);
assert.equal(GOALS.length,4);
assert.ok(Math.abs(Object.values(WEIGHTS).reduce((a,b)=>a+b,0)-1)<1e-9);
assert.equal(preferenceFit({pace:'slow',approach:'step',interaction:'encouraging'},{pace:['slow'],approach:['step'],interaction:['encouraging']}),100);
assert.equal(preferenceFit({pace:'any',approach:'any',interaction:'any'},{pace:['slow'],approach:['step'],interaction:['encouraging']}),50);
assert.equal(preferenceFit({pace:'fast',approach:'concept',interaction:'independent'},{pace:['slow'],approach:['step'],interaction:['encouraging']}),25);
let ranked=matchTutors(student,tutors);
assert.ok(ranked.length>0&&ranked.length<=3);
assert.ok(ranked.every(x=>approvedToTeach(x,x.matchedOffering.subject,student.grade)));
assert.ok(ranked.every(x=>x.price<=student.budget));
assert.ok(ranked.every((x,i)=>i===0||ranked[i-1].fit.score>=x.fit.score));
const scoreBase=matchTutors(student,[tutors[0]])[0].fit.score;
const scoreChanged=matchTutors({...student,approach:'concept',interaction:'independent',pace:'fast'},[tutors[0]])[0].fit.score;
assert.notEqual(scoreBase,scoreChanged,'3 Student preferences must affect weighted scores');
assert.equal(matchTutors({...student,budget:100},tutors).length,0);
assert.equal(matchTutors({...student,subject:'Thai'},tutors).length,0);
assert.equal(matchTutors({...student,grade:'M.1'},[tutors[0]]).length,0);
const unverified={...structuredClone(tutors[0]),verified:false,price:100};
assert.equal(matchTutors(student,[unverified]).length,0);
const noSubject={...structuredClone(tutors[0]),approvedScopes:[]};
assert.equal(matchTutors(student,[noSubject]).length,0);
const pendingPhysics={...structuredClone(tutors[0]),approvedScopes:[...tutors[0].approvedScopes,{subject:'Physics',grades:['M.4'],status:'pending'}],offerings:[...tutors[0].offerings,{id:'pending',subject:'Physics',grades:['M.4'],goalType:'school-grade',price:400,schedule:['thu'],formats:['one'],published:true}]};
assert.equal(matchTutors({...student,subject:'Physics'},[pendingPhysics]).length,0,'Pending new Physics cannot match');
assert.equal(matchTutors(student,[pendingPhysics]).length,1,'Pending Physics must not block already approved Mathematics');
pendingPhysics.approvedScopes[1].status='approved';
assert.equal(matchTutors({...student,subject:'Physics'},[pendingPhysics]).length,1);
const newCourse={...structuredClone(tutors[0]),offerings:[...tutors[0].offerings,{id:'new-math',subject:'Mathematics',grades:['M.4'],goalType:'school-grade',price:350,schedule:['thu'],formats:['one'],published:true}]};
assert.equal(matchTutors(student,[newCourse]).length,1,'Creating an approved course must not require another verification');
const draftCourse={...newCourse,offerings:[{...newCourse.offerings[1],published:false}]};
assert.equal(matchTutors(student,[draftCourse]).length,0);
const groupStudent={...student,format:'group'};
assert.ok(matchGroups(groupStudent,CATALOG.groups,tutors).length>0);
assert.equal(matchGroups(groupStudent,CATALOG.groups,[]).length,0);
const p=defaultPlan([]);assert.equal(planProgress(p),0);p[0].completed=true;assert.ok(planProgress(p)>0);
let state={learningPlans:{}};ensurePlan(state,'test-student',[]);assert.ok(state.learningPlans['test-student'].length);
console.log('PASS: 3 preference questions, goal-based ranking, subject/grade approval, pending subjects, instant course publish, and group matching');
